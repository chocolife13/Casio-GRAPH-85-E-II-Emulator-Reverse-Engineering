#!/usr/bin/env python3
"""Generate native/src/font6x8.h from a Linux console PSF font.

The Graph 85 LCD is 128x64 pixels and the original OS uses a 6x8 character
cell (21 columns x 8 rows).  The console font is 8x8; each glyph is trimmed
of empty columns and padded/centred to six columns.
"""
import gzip
import struct
import sys


def load_psf(path):
    data = gzip.open(path, "rb").read() if path.endswith(".gz") else open(path, "rb").read()
    if data[:2] == b"\x36\x04":  # PSF1
        mode, charsize = data[2], data[3]
        count = 512 if mode & 1 else 256
        offset = 4
        glyphs = [data[offset + i * charsize: offset + (i + 1) * charsize]
                  for i in range(count)]
    elif data[:4] == b"\x72\xb5\x4a\x86":  # PSF2
        hdr = struct.unpack_from("<IIIIIIII", data, 4)
        header_size, count, charsize = hdr[1], hdr[3], hdr[4]
        offset = header_size
        glyphs = [data[offset + i * charsize: offset + (i + 1) * charsize]
                  for i in range(count)]
    else:
        raise ValueError("not a PSF font")
    return glyphs, charsize


def trim(glyph, width=8, height=8):
    # glyph is column-major? PSF stores rows, each row width/8 bytes.
    rows = list(glyph[:height])
    cols = []
    for x in range(width):
        col = 0
        for y in range(height):
            if rows[y] & (0x80 >> x):
                col |= 1 << y
        cols.append(col)
    while cols and cols[0] == 0:
        cols.pop(0)
    while cols and cols[-1] == 0:
        cols.pop()
    return cols


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/kbd/consolefonts/Cyr_a8x8.psfu.gz"
    dst = sys.argv[2] if len(sys.argv) > 2 else "native/src/font6x8.h"
    glyphs, charsize = load_psf(src)
    height = 8
    out = []
    for code in range(32, 127):
        cols = trim(glyphs[code], 8, height)
        if len(cols) > 6:
            cols = cols[:6]
        while len(cols) < 6:
            cols.append(0)
        out.append((code, cols))
    with open(dst, "w") as f:
        f.write("/* Generated by tools/make_font.py from %s.\n" % src)
        f.write(" * 6x8 console font, one byte per column, bit 0 = top row. */\n")
        f.write("#ifndef FONT6X8_H\n#define FONT6X8_H\n\n")
        f.write("static const unsigned char font6x8[95][6] = {\n")
        for code, cols in out:
            ch = chr(code)
            label = {"'": "\\'", "\\": "\\\\"}.get(ch, ch if 32 <= code < 127 else "?")
            f.write("    {%s}, /* %3d %s */\n" % (", ".join("0x%02x" % c for c in cols), code, label))
        f.write("};\n\n#endif\n")
    print("wrote %s (%d glyphs)" % (dst, len(out)))


if __name__ == "__main__":
    main()
